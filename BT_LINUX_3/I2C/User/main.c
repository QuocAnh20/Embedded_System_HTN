void I2C1_Init_Hardware(void) {
    GPIO_InitTypeDef GPIO_InitStructure;
    I2C_InitTypeDef I2C_InitStructure;

    RCC_APB2PeriphClockCmd(RCC_APB2Periph_GPIOB | RCC_APB2Periph_AFIO, ENABLE);
    RCC_APB1PeriphClockCmd(RCC_APB1Periph_I2C1, ENABLE);

    GPIO_InitStructure.GPIO_Pin = GPIO_Pin_6 | GPIO_Pin_7; // PB6 = SCL, PB7 = SDA
    GPIO_InitStructure.GPIO_Speed = GPIO_Speed_50MHz;
    GPIO_InitStructure.GPIO_Mode = GPIO_Mode_AF_OD;
    GPIO_Init(GPIOB, &GPIO_InitStructure);

    I2C_InitStructure.I2C_Mode = I2C_Mode_I2C;
    I2C_InitStructure.I2C_DutyCycle = I2C_DutyCycle_2;
    I2C_InitStructure.I2C_OwnAddress1 = 0x00;
    I2C_InitStructure.I2C_Ack = I2C_Ack_Enable;
    I2C_InitStructure.I2C_AcknowledgedAddress = I2C_AcknowledgedAddress_7bit;
    I2C_InitStructure.I2C_ClockSpeed = 400000;

    I2C_Init(I2C1, &I2C_InitStructure);
    I2C_Cmd(I2C1, ENABLE);
}

void SSD1306_WriteCommand(uint8_t cmd) {
    while(I2C_GetFlagStatus(I2C1, I2C_FLAG_BUSY));
    I2C_GenerateSTART(I2C1, ENABLE);
    while(!I2C_CheckEvent(I2C1, I2C_EVENT_MASTER_MODE_SELECT));

    I2C_Send7bitAddress(I2C1, SSD1306_I2C_ADDR, I2C_Direction_Transmitter);
    while(!I2C_CheckEvent(I2C1, I2C_EVENT_MASTER_TRANSMITTER_MODE_SELECTED));

    I2C_SendData(I2C1, 0x00); 
    while(!I2C_CheckEvent(I2C1, I2C_EVENT_MASTER_BYTE_TRANSMITTING));

    I2C_SendData(I2C1, cmd);
    while(!I2C_CheckEvent(I2C1, I2C_EVENT_MASTER_BYTE_TRANSMITTED));

    I2C_GenerateSTOP(I2C1, ENABLE);
}

void SSD1306_WriteData(uint8_t data) {
    while(I2C_GetFlagStatus(I2C1, I2C_FLAG_BUSY));
    I2C_GenerateSTART(I2C1, ENABLE);
    while(!I2C_CheckEvent(I2C1, I2C_EVENT_MASTER_MODE_SELECT));

    I2C_Send7bitAddress(I2C1, SSD1306_I2C_ADDR, I2C_Direction_Transmitter);
    while(!I2C_CheckEvent(I2C1, I2C_EVENT_MASTER_TRANSMITTER_MODE_SELECTED));

    I2C_SendData(I2C1, 0x40); 
    while(!I2C_CheckEvent(I2C1, I2C_EVENT_MASTER_BYTE_TRANSMITTING));

    I2C_SendData(I2C1, data);
    while(!I2C_CheckEvent(I2C1, I2C_EVENT_MASTER_BYTE_TRANSMITTED));

    I2C_GenerateSTOP(I2C1, ENABLE);
}

void SSD1306_Init(void) {
    I2C1_Init_Hardware();
    SSD1306_WriteCommand(0xAE); // Turn off display
    SSD1306_WriteCommand(0x20); // Set Memory Addressing Mode
    SSD1306_WriteCommand(0x00); // 0x00: Horizontal Addressing
    SSD1306_WriteCommand(0x8D); // Charge Pump
    SSD1306_WriteCommand(0x14); // Enable Charge Pump
    SSD1306_WriteCommand(0xAF); // Turn on display
}

void SSD1306_Clear(void) {
    SSD1306_WriteCommand(0x21); SSD1306_WriteCommand(0); SSD1306_WriteCommand(127);
    SSD1306_WriteCommand(0x22); SSD1306_WriteCommand(0); SSD1306_WriteCommand(7);
    for (uint16_t i = 0; i < 1024; i++) {
        SSD1306_WriteData(0x00);
    }
}

void SSD1306_SetCursor(uint8_t page, uint8_t column) {
    SSD1306_WriteCommand(0x22); 
    SSD1306_WriteCommand(page); 
    SSD1306_WriteCommand(7);
    
    SSD1306_WriteCommand(0x21); 
    SSD1306_WriteCommand(column); 
    SSD1306_WriteCommand(127);
}

void SSD1306_PutChar(char c) {
    if (c < 32 || c > 126) c = ' ';
    uint8_t idx = c - 32;
    for (uint8_t i = 0; i < 5; i++) {
        SSD1306_WriteData(Font5x7[idx][i]);
    }
    SSD1306_WriteData(0x00);
}

void SSD1306_PrintString(char* str) {
    while (*str) {
        SSD1306_PutChar(*str++);
    }
}

